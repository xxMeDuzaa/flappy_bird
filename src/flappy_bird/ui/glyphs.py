#: Píxeles encendidos de cada carácter como coordenadas ``(columna, fila)``.
GLYPHS: dict[str, frozenset[tuple[int, int]]] = {
    char: frozenset(
        (col, row)
        for row, line in enumerate(rows.split())
        for col, cell in enumerate(line)
        if cell == "#"
    )
    for char, rows in _RAW.items()
}

FALLBACK = "?"


def text_size(text: str) -> tuple[int, int]:
    """Tamaño en píxeles de la fuente (sin escalar) que ocupa ``text``."""
    if not text:
        return 0, GLYPH_HEIGHT
    advance = GLYPH_WIDTH + LETTER_SPACING
    return len(text) * advance - LETTER_SPACING, GLYPH_HEIGHT


def text_pixels(text: str) -> list[tuple[int, int]]:
    """Coordenadas ``(x, y)`` de cada píxel encendido al escribir ``text`` en mayúsculas.

    Los caracteres que la fuente no tiene se muestran como ``?``.
    """
    advance = GLYPH_WIDTH + LETTER_SPACING
    pixels: list[tuple[int, int]] = []
    for index, char in enumerate(text.upper()):
        glyph = GLYPHS.get(char, GLYPHS[FALLBACK])
        offset = index * advance
        pixels.extend((offset + col, row) for col, row in glyph)
    return pixels
